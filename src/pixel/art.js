// Rechte Hälfte eine Stufe dunkler (Licht kommt von links)
const SHADE = { Y: 'y', y: 'u', u: 'U', U: 'j', M: 'm', m: 'n', n: 'N', B: 'b', b: 'v', G: 'g', g: 'f', R: 'r', r: 'q', E: 'e', e: 'i', A: 'a', a: 'c', P: 'p', p: 'x', W: 't', t: 'T', S: 's', s: 'z', L: 'l', l: 'd' };

export function mirror(half, { shade = true, odd = false, map = SHADE } = {}) {
  return half.map((row) => {
    const right = [...row].reverse().slice(odd ? 1 : 0).map((ch) => (shade ? map[ch] ?? ch : ch));
    return row + right.join('');
  });
}

